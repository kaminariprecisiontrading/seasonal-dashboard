"""
Phase 3 — Dashboard data export (Kaminari Market Profiling System)

Bundles a single asset's stats_engine.py + profile_taxonomy.py JSON outputs
into one static dashboard/data/<asset>.js file, defining a single global
(e.g. `const GBPUSD_DATA = {...}`) that the dashboard HTML pages load via a
plain <script> tag — same pattern as the sibling Kaminari Seasonals
Dashboard's data/*.js files, chosen so the dashboard works from a plain
file:// open with no server/build step and no fetch()/CORS concerns.

Usage:
    python3 build_dashboard_data.py <stats_json> <profile_summary_json> <output_js> --asset GBPUSD
"""

import json
import argparse


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("stats_json")
    ap.add_argument("profile_summary_json")
    ap.add_argument("output_js")
    ap.add_argument("--asset", required=True)
    args = ap.parse_args()

    with open(args.stats_json) as f:
        stats = json.load(f)
    with open(args.profile_summary_json) as f:
        profiles = json.load(f)

    bundle = {"asset": args.asset, "stats": stats, "profiles": profiles}
    var_name = f"{args.asset.upper()}_DATA"

    with open(args.output_js, "w") as f:
        f.write(f"// Auto-generated by pipeline/build_dashboard_data.py — do not edit by hand.\n")
        f.write(f"const {var_name} = ")
        json.dump(bundle, f, indent=2)
        f.write(";\n")

    print(f"wrote {args.output_js} ({var_name})")


if __name__ == "__main__":
    main()
