/**
 * gen_month_signals.js — generates data/month_signals.js: each live asset's
 * month-level combined signal and conviction, read from its data file's MONTHS[]
 * (`combined`: bull | bear | chop | flip, `stars`: 1-5). Used by the Heatmap's
 * Months view (KptSignals.getMonthSignal) so it can show the month-level verdict
 * without loading all 98 data files.
 *
 * Run from the repo root after changing any data/<asset>.js:
 *   node scripts/gen_month_signals.js
 */
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const ROOT = path.join(__dirname, '..', 'frontend');  // site root — the published directory (v1.27)
const ids = fs.readdirSync(path.join(ROOT, 'assets')).filter(f => f.endsWith('.html')).map(f => f.replace('.html', '')).sort();
const out = {};
ids.forEach(id => {
  const sb = { window: {} };
  vm.createContext(sb);
  vm.runInContext(fs.readFileSync(path.join(ROOT, 'data', id + '.js'), 'utf8') + ';this.__M = MONTHS;', sb);
  const M = sb.__M;
  if (!Array.isArray(M) || M.length !== 12) throw new Error(id + ': MONTHS[] must have 12 entries');
  out[id] = M.map(m => {
    const c = String(m.combined || '').toLowerCase();
    if (!/^(bull|bear|chop|flip)$/.test(c)) throw new Error(id + ' ' + m.month + ': unexpected combined "' + m.combined + '"');
    return [c, Math.max(0, Math.min(5, +m.stars || 0))];
  });
});
const js = [
  '// data/month_signals.js — AUTO-GENERATED by scripts/gen_month_signals.js from each data/<asset>.js',
  '// MONTHS[] (month-level `combined` + `stars`). Do not hand-edit. Format: id -> 12 x [signal, conviction].',
  'window.KPT_MONTH_SIGNALS = ' + JSON.stringify(out) + ';',
  ''
].join('\n');
fs.writeFileSync(path.join(ROOT, 'data', 'month_signals.js'), js, 'utf8');
console.log('assets: ' + ids.length + ', months: ' + ids.length * 12);
