/**
 * gen_signals_manifest.js — regenerates data/signals_manifest.js from every asset's data
 * file: SIGNALS_MANIFEST[id] = the 48 week `com` strings (Jan-Wk1 … Dec-Wk4) of that
 * asset's MONTHS[], plus SIGNALS_GENERATED (the freshness timestamp shown on the dashboard).
 *
 * The original generator was never committed (see scripts/README.md); this reconstruction
 * (v1.26) keeps the same output format and was written after a check found the committed
 * manifest had drifted from five data files (austbills3m, austbonds10, austbonds3,
 * longgilt, shortsterling — 192 weeks), so the dashboard cards disagreed with those
 * assets' own pages. The data files are the source of truth.
 *
 * Run from the site root after changing any data/<asset>.js:
 *   node scripts/gen_signals_manifest.js           (writes the file)
 *   node scripts/gen_signals_manifest.js --check   (exit 1 if the manifest is out of date)
 */
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const SITE = path.join(__dirname, '..');
const OUT = path.join(SITE, 'data', 'signals_manifest.js');
const ids = fs.readdirSync(path.join(SITE, 'assets')).filter(f => f.endsWith('.html')).map(f => f.replace('.html', ''));

// Keep the existing key order (dashboard order) and append any new assets at the end.
const prev = (() => {
  try { const sb = {}; vm.createContext(sb); vm.runInContext(fs.readFileSync(OUT, 'utf8') + ';this.M=SIGNALS_MANIFEST', sb); return sb.M; }
  catch (e) { return {}; }
})();
const order = Object.keys(prev).filter(id => ids.includes(id)).concat(ids.filter(id => !(id in prev)).sort());

const manifest = {};
order.forEach(id => {
  const sb = { window: {} };
  vm.createContext(sb);
  vm.runInContext(fs.readFileSync(path.join(SITE, 'data', id + '.js'), 'utf8') + ';this.__M = MONTHS;', sb);
  const coms = [];
  sb.__M.forEach(m => m.weeks.forEach(w => coms.push(w.com || '')));
  if (coms.length !== 48) throw new Error(id + ': expected 48 weeks, got ' + coms.length);
  manifest[id] = coms;
});

const changed = order.filter(id => JSON.stringify(prev[id]) !== JSON.stringify(manifest[id]));
if (process.argv.includes('--check')) {
  console.log(changed.length ? 'OUT OF DATE: ' + changed.join(', ') : 'manifest up to date (' + order.length + ' assets)');
  process.exit(changed.length ? 1 : 0);
}

const stamp = new Date().toISOString();
const body = order.map(id => {
  const rows = [];
  for (let i = 0; i < 48; i += 4) rows.push('    ' + manifest[id].slice(i, i + 4).map(c => JSON.stringify(c)).join(', '));
  return '  ' + JSON.stringify(id) + ': [\n' + rows.join(',\n') + '\n  ]';
}).join(',\n');
fs.writeFileSync(OUT, [
  '// signals_manifest.js — AUTO-GENERATED by scripts/gen_signals_manifest.js',
  '// Generated: ' + stamp,
  '// Format: SIGNALS_MANIFEST[id] = 48-element array [Jan-Wk1, Jan-Wk2, ..., Dec-Wk4]',
  '// com strings: "LONG ★★★★", "SHORT ★★★", "CHOP", "FLIP ★★" etc.',
  '// js/signals.js reads [currentMonth * 4 + currentWeek] to derive the live signal.',
  '',
  '/* global SIGNALS_MANIFEST, SIGNALS_GENERATED */',
  "const SIGNALS_GENERATED = '" + stamp + "';",
  '',
  'const SIGNALS_MANIFEST = {',
  body,
  '};',
  ''
].join('\n'), 'utf8');
console.log('wrote data/signals_manifest.js: ' + order.length + ' assets; changed vs previous: ' + (changed.join(', ') || 'none'));
