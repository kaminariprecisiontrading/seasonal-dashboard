/**
 * gen_asset_index.js — Generates data/asset_index.js, the shared asset registry
 * (id, ticker, name, component/timeframe badges, accent colour, group, status)
 * that js/signals.js and every page outside the dashboard use.
 *
 * Source of truth is the dashboard's own card markup (dashboard.html): every
 * `.asset-card` under its `.grid-section` heading. Generating from there (rather
 * than hand-maintaining a second list) means a new card on the dashboard shows up
 * on the landing page, This Week and the Heatmap after one re-run — no drift.
 *
 * Run from seasonal-dashboard/ root after adding/renaming a dashboard card:
 *   node scripts/gen_asset_index.js
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const html = fs.readFileSync(path.join(ROOT, 'dashboard.html'), 'utf8');

function text(s) {
  return s.replace(/<[^>]+>/g, '').replace(/&amp;/g, '&').replace(/&nbsp;/g, ' ').trim();
}

// Walk the document in order: source blocks, grid-section headings and cards.
const re = /<div class="source-block" id="([^"]+)"|<div class="grid-section" id="([^"]+)">([\s\S]*?)<\/div>|<a class="asset-card (status-[a-z]+)" href="([^"]*)" style="--card-accent:([^;"]+);?">([\s\S]*?)<\/a>/g;

let block = null, group = null;
const groups = [];
const assets = [];
let m;
while ((m = re.exec(html))) {
  if (m[1]) { block = m[1]; continue; }
  if (m[2]) {
    group = { id: m[2], label: text(m[3]), block: block };
    groups.push(group);
    continue;
  }
  const status = m[4].replace('status-', '');
  const href = m[5];
  const body = m[7];
  const ticker = text((body.match(/<div class="card-ticker">([\s\S]*?)<\/div>/) || [])[1] || '');
  const name = text((body.match(/<div class="card-name">([\s\S]*?)<\/div>/) || [])[1] || '');
  const badges = [];
  const meta = (body.match(/<div class="card-meta">([\s\S]*?)<\/div>/) || [])[1] || '';
  meta.replace(/<span class="card-badge[^"]*">([\s\S]*?)<\/span>/g, function (_, b) { badges.push(text(b)); return _; });
  const idm = href.match(/assets\/([^./?#]+)\.html/);
  assets.push({
    id: idm ? idm[1] : null,
    ticker: ticker,
    name: name,
    badges: badges,
    accent: m[6].trim(),
    group: group ? group.id : null,
    block: block,
    status: status === 'complete' ? 'live' : status
  });
}

const live = assets.filter(a => a.status === 'live');
const missingId = live.filter(a => !a.id);
if (missingId.length) throw new Error('Live card(s) without an assets/<id>.html href: ' + missingId.map(a => a.ticker).join(', '));

const out = [
  '// data/asset_index.js — AUTO-GENERATED by scripts/gen_asset_index.js from dashboard.html\'s',
  '// asset cards. Do not hand-edit: change the dashboard card, then re-run the script.',
  '// KPT_ASSET_GROUPS: dashboard sections in page order ({id, label, block}).',
  '// KPT_ASSETS: every card in page order. status "live" (has a page) or "planned".',
  'window.KPT_ASSET_GROUPS = ' + JSON.stringify(groups) + ';',
  'window.KPT_ASSETS = ' + JSON.stringify(assets.map(a => a.status === 'live' ? a : Object.assign({}, a, { id: null })), null, 0) + ';',
  ''
].join('\n');
fs.writeFileSync(path.join(ROOT, 'data', 'asset_index.js'), out, 'utf8');

const byBlock = {};
live.forEach(a => { byBlock[a.block] = (byBlock[a.block] || 0) + 1; });
console.log('groups:', groups.length, '| live:', live.length, byBlock, '| planned:', assets.length - live.length);
