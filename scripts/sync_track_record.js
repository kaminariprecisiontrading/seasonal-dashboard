/**
 * sync_track_record.js — copies the graded signal history from the sibling
 * pipeline (backend/output/track_record.json, written by
 * pipeline/grade_signals.py) into data/track_record.js as window.KPT_TRACK_RECORD,
 * for the /track-record page. Same pattern as scripts/sync_profiling_data.js.
 *
 * Run from the repo root after re-running grade_signals.py:
 *   node scripts/sync_track_record.js
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..', 'frontend');  // site root — the published directory (v1.27)
const SRC = path.join(__dirname, '..', 'backend', 'output', 'track_record.json');
const data = JSON.parse(fs.readFileSync(SRC, 'utf8'));
if (!Array.isArray(data.rows) || !Array.isArray(data.assets)) throw new Error('unexpected track_record.json shape');
fs.writeFileSync(path.join(ROOT, 'data', 'track_record.js'), [
  '// data/track_record.js — AUTO-GENERATED by scripts/sync_track_record.js from',
  '// backend/output/track_record.json (backend/pipeline/grade_signals.py). Do not hand-edit.',
  '// rows: [week (Monday), assetIndex, signal, conviction, moveAdr (graded part of the week), result H|M|-, source b(ackfill)|l(ive), FLIP post-turn direction BULL|BEAR (empty otherwise)]',
  'window.KPT_TRACK_RECORD = ' + JSON.stringify(data) + ';',
  ''
].join('\n'), 'utf8');
const graded = data.rows.filter(r => r[5] !== '-').length;
console.log('synced ' + data.rows.length + ' rows (' + graded + ' graded), data as of ' + data.asOf);
